/**
 * The archive lock index (#3398; neutral freeze-announcement design §4.3 and §10 item 1).
 *
 * One generated static document at `/lock-index.json` in the served public archive, listing the
 * locks this workspace has announced: for each, the digest path of the sealed Run record, the
 * signed archive page that announced it, every AnchorEvidence record the run carries, and the
 * run's public bundle identities.
 *
 * It is presentation over data that already ships, and deliberately nothing more:
 *
 * - **Not a registry and not a trust claim.** It is this publisher's own rendering of its own
 *   announcements, served from the same tree it indexes, and the document says so in its own
 *   bytes. It adds no party who could contradict the publisher (design §4.2).
 * - **Rows link, they do not assert.** A path is written only when the exact bytes it names are
 *   present in the served tree and hash to their digest. AnchorEvidence records and bundles are
 *   not served by this archive today, so their digests are listed with a `null` path rather than
 *   with a location nothing answers.
 * - **Append-only in spirit.** This file is the one object here that is rewritten; everything it
 *   points at is digest-addressed or signed and never changes. Regeneration is a pure function of
 *   three inputs: the committed source chain, the workspace's run records, and which exact bytes
 *   the served tree holds (a path is written only for bytes present there). Stable ordering, no
 *   clock, and no write at all when the bytes would not change.
 * - **Never sealed.** It is written to the serving root only, never to the sealed store, never
 *   announced, and outside the Record Discovery path grammar, so no bundle, claim package,
 *   registration closure, or reader-pinned byte comparison can include it.
 *
 * It is regenerated after every registration and when `publication serve` starts, so an anchor
 * or bundle recorded after a lock's registration appears at the next of either; a server that is
 * already running does not rebuild it. A registration whose rebuild fails says so on its result
 * (`lockIndexRefreshFailure`) rather than failing.
 */

import { constants, readdirSync } from "node:fs";
import { open } from "node:fs/promises";
import { join } from "node:path";
import { RUN_MEDIA_TYPE } from "@jinn-network/benchmarking-records";
import { archivePagePath, recordPath } from "@jinn-network/record-discovery-protocol";
import { REVALIDATE_CACHE_CONTROL, createFsBlobStore } from "@jinn-network/record-discovery-transport-http";
import { publicationServeRoot, runsDir } from "../workspace/layout.js";
import { sha256Hex } from "../workspace/sealed-store.js";
import { createWorkspacePublicationSource, withWorkspacePublicationSourceLock } from "./publication-source.js";
import { readRunState, type RunState } from "./state.js";

export const PUBLICATION_LOCK_INDEX_PATH = "/lock-index.json";
export const PUBLICATION_LOCK_INDEX_FORMAT = "colophon-archive-lock-index/1";
const PUBLICATION_LOCK_INDEX_MEDIA_TYPE = "application/json";

const STATEMENT = "Presentation index generated by this archive's publisher over its own announced locks. "
  + "It is not a registry, not a neutral surface, and not a trust claim: every path it lists is digest-addressed "
  + "or signed and is checked by its own bytes, not by this file. A path is given only when its exact bytes are "
  + "served by this archive; a null path means they are not served here. This file is rewritten when it is "
  + "regenerated; nothing it points at ever changes.";

interface LockIndexRow {
  readonly lockSha256: string;
  readonly source: { readonly agent: string; readonly name: string };
  readonly sequence: string;
  readonly entryPath: string | null;
  readonly runPath: string | null;
  readonly anchors: readonly {
    readonly subject: string;
    readonly provider: string;
    readonly recordSha256: string;
    readonly path: string | null;
  }[];
  readonly bundles: readonly { readonly identity: string; readonly path: string | null }[];
}

/** Code-unit order, never `localeCompare`: the same inputs must give the same bytes on any host. */
function byCodeUnit(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

/** Every run record this workspace holds that parses; an unreadable one is its own verb's business. */
function readRunStates(workspaceDir: string): RunState[] {
  let files: readonly string[];
  try { files = readdirSync(runsDir(workspaceDir)); } catch { return []; }
  const states: RunState[] = [];
  for (const file of files) {
    if (!file.endsWith(".json") || file.endsWith(".cancel-requested.json")) continue;
    try {
      const state = readRunState(workspaceDir, file.slice(0, -".json".length));
      if (state !== undefined) states.push(state);
    } catch { /* skipped, exactly as source-name resolution skips it */ }
  }
  return states;
}

/**
 * Builds the index bytes from the committed source chain, or `undefined` when no lock has been
 * announced. It reads the committed position only: it never recovers or appends to a source.
 */
export async function buildWorkspacePublicationLockIndex(workspaceDir: string): Promise<Uint8Array | undefined> {
  const blobs = createFsBlobStore(publicationServeRoot(workspaceDir));
  const servedDigestPath = async (hex: string): Promise<string | null> => {
    for (const path of [recordPath(`sha256:${hex}`), `/publication-artifacts/sha256/${hex}`]) {
      const stored = await blobs.get(path);
      if (stored !== undefined && sha256Hex(stored.bytes) === hex) return path;
    }
    return null;
  };

  const states = readRunStates(workspaceDir);
  const carried = new Map<string, { anchors: Map<string, NonNullable<RunState["anchors"]>[number]>; bundles: Set<string> }>();
  for (const state of states) {
    if (state.runSha256 === undefined) continue;
    const entry = carried.get(state.runSha256) ?? { anchors: new Map(), bundles: new Set<string>() };
    for (const anchor of state.anchors ?? []) entry.anchors.set(anchor.recordSha256, anchor);
    if (state.bundleIdentity !== undefined) entry.bundles.add(state.bundleIdentity);
    for (const additional of state.additionalBundles ?? []) entry.bundles.add(additional.bundleIdentity);
    carried.set(state.runSha256, entry);
  }

  const key = (row: Pick<LockIndexRow, "source" | "sequence">): string => `${row.source.agent}\u001f${row.source.name}\u001f${row.sequence}`;
  const rows = new Map<string, LockIndexRow>();
  const sourceNames = new Set(states.flatMap((state) => (state.publication === undefined ? [] : [state.publication.source.name])));
  for (const name of sourceNames) {
    const source = createWorkspacePublicationSource(workspaceDir, name);
    const committed = await source.writer.readState();
    for (const announced of Object.values(committed?.announcements ?? {})) {
      const record = announced.receipt.record;
      if (announced.action !== "available" || record === undefined || record.contentType !== RUN_MEDIA_TYPE) continue;
      const lockSha256 = record.digest.slice("sha256:".length);
      const earlier = rows.get(lockSha256);
      // One row per lock: a Run announced twice is listed once, at the position that sorts first.
      const position = { source: { agent: source.source.agent, name }, sequence: announced.receipt.sequence };
      if (earlier !== undefined && byCodeUnit(key(earlier), key(position)) <= 0) continue;
      const pagePath = archivePagePath(name, announced.receipt.page);
      const extra = carried.get(lockSha256);
      const anchors = [...(extra?.anchors.values() ?? [])].sort((left, right) => byCodeUnit(left.recordSha256, right.recordSha256));
      const bundles = [...(extra?.bundles ?? [])].sort(byCodeUnit);
      rows.set(lockSha256, {
        lockSha256,
        ...position,
        entryPath: (await blobs.get(pagePath)) === undefined ? null : pagePath,
        runPath: await servedDigestPath(lockSha256),
        anchors: await Promise.all(anchors.map(async (anchor) => ({
          subject: anchor.subject,
          provider: anchor.provider,
          recordSha256: anchor.recordSha256,
          path: await servedDigestPath(anchor.recordSha256),
        }))),
        bundles: await Promise.all(bundles.map(async (identity) => ({ identity, path: await servedDigestPath(identity) }))),
      });
    }
  }
  if (rows.size === 0) return undefined;

  const locks = [...rows.values()].sort((left, right) => byCodeUnit(key(left), key(right)));
  return new TextEncoder().encode(`${JSON.stringify({ format: PUBLICATION_LOCK_INDEX_FORMAT, statement: STATEMENT, locks }, null, 2)}\n`);
}

/**
 * Regenerates `/lock-index.json` in the serving root. Returns `false`, writing nothing, when no
 * lock has been announced. Taken under the source lock so it never reads a position mid-append
 * and two regenerations cannot interleave.
 */
export async function refreshWorkspacePublicationLockIndex(
  workspaceDir: string,
  onContended?: () => void,
): Promise<boolean> {
  return withWorkspacePublicationSourceLock(workspaceDir, async () => {
    const bytes = await buildWorkspacePublicationLockIndex(workspaceDir);
    if (bytes === undefined) return false;
    const blobs = createFsBlobStore(publicationServeRoot(workspaceDir));
    const current = await blobs.get(PUBLICATION_LOCK_INDEX_PATH);
    if (current === undefined || sha256Hex(current.bytes) !== sha256Hex(bytes)) {
      await blobs.put(PUBLICATION_LOCK_INDEX_PATH, bytes, PUBLICATION_LOCK_INDEX_MEDIA_TYPE);
    }
    return true;
  }, onContended);
}

/**
 * Answers `/lock-index.json` and returns `undefined` for every other path, so a caller can place
 * it in front of the archive handler. Read failures are indistinguishable from absence, as they
 * are on the archive handler.
 */
export function createPublicationLockIndexHttpHandler(
  workspaceDir: string,
): (request: Request) => Promise<Response | undefined> {
  return async (request) => {
    let pathname: string;
    try { pathname = new URL(request.url).pathname; } catch { return undefined; }
    if (pathname !== PUBLICATION_LOCK_INDEX_PATH) return undefined;
    if (request.method !== "GET" && request.method !== "HEAD") {
      return new Response(null, { status: 405, headers: { allow: "GET, HEAD" } });
    }
    let bytes: Uint8Array;
    try {
      // A fixed name at the root, opened without following a link: a symlink planted here must
      // not serve bytes from outside the archive.
      const handle = await open(join(publicationServeRoot(workspaceDir), PUBLICATION_LOCK_INDEX_PATH), constants.O_RDONLY | constants.O_NOFOLLOW);
      try {
        if (!(await handle.stat()).isFile()) return new Response(null, { status: 404 });
        bytes = new Uint8Array(await handle.readFile());
      } finally { await handle.close(); }
    } catch {
      return new Response(null, { status: 404 });
    }
    return new Response(request.method === "HEAD" ? null : bytes, {
      status: 200,
      headers: {
        "content-type": PUBLICATION_LOCK_INDEX_MEDIA_TYPE,
        "cache-control": REVALIDATE_CACHE_CONTROL,
        "x-content-type-options": "nosniff",
      },
    });
  };
}
